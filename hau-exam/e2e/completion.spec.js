test('change password rejects a wrong current password and succeeds with the correct one', async ({ page, gateway }) => {
  await gateway.login('USER')
  await page.getByLabel('Mở menu tài khoản').click()
  await page.getByRole('button', { name: 'Đổi mật khẩu' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.locator('input[autocomplete="current-password"]').fill('wrong-password')
  await dialog.locator('input[autocomplete="new-password"]').nth(0).fill('new-password-123')
  await dialog.locator('input[autocomplete="new-password"]').nth(1).fill('new-password-123')
  await page.getByRole('dialog').getByRole('button', { name: 'Đổi mật khẩu' }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('không đúng')
  await dialog.locator('input[autocomplete="current-password"]').fill('test-password')
  await page.getByRole('dialog').getByRole('button', { name: 'Đổi mật khẩu' }).click()
  await expect(page.locator('.notification-toast').filter({ hasText: 'Đổi mật khẩu thành công' })).toBeVisible()
  await expect(page).toHaveURL(/login/, { timeout: 3000 })
})
